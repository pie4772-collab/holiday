CREATE TABLE IF NOT EXISTS attendance_records (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id      INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE,
  work_date        TEXT COLLATE "C" NOT NULL,
  check_in_at      TEXT COLLATE "C",
  check_in_ip      TEXT COLLATE "C",
  check_in_type    TEXT COLLATE "C",
  check_in_place   TEXT COLLATE "C",
  check_out_at     TEXT COLLATE "C",
  check_out_ip     TEXT COLLATE "C",
  check_out_type   TEXT COLLATE "C",
  check_out_place  TEXT COLLATE "C",
  corrected        INTEGER NOT NULL DEFAULT 0,
  note             TEXT COLLATE "C",
  created_at       TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at       TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (employee_id, work_date)
);

CREATE INDEX IF NOT EXISTS idx_attendance_records_date ON attendance_records(work_date);

CREATE TABLE IF NOT EXISTS attendance_logs (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id  INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE,
  work_date    TEXT COLLATE "C" NOT NULL,
  action       TEXT COLLATE "C" NOT NULL,
  occurred_at  TEXT COLLATE "C" NOT NULL,
  ip           TEXT COLLATE "C",
  work_type    TEXT COLLATE "C",
  place        TEXT COLLATE "C",
  actor_id     INTEGER,
  reason       TEXT COLLATE "C",
  detail       TEXT COLLATE "C"
);

CREATE INDEX IF NOT EXISTS idx_attendance_logs_employee ON attendance_logs(employee_id, work_date);

CREATE TABLE IF NOT EXISTS attendance_closings (
  year       INTEGER NOT NULL,
  month      INTEGER NOT NULL,
  closed_by  INTEGER,
  closed_at  TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  PRIMARY KEY (year, month)
);
