CREATE TABLE IF NOT EXISTS attendance_sites (
  workplace_code  TEXT COLLATE "C" PRIMARY KEY,
  name            TEXT COLLATE "C" NOT NULL,
  work_start      TEXT COLLATE "C" NOT NULL,
  work_end        TEXT COLLATE "C" NOT NULL,
  lunch_start     TEXT COLLATE "C" NOT NULL,
  lunch_end       TEXT COLLATE "C" NOT NULL,
  grace_minutes   INTEGER NOT NULL DEFAULT 15,
  ip_ranges       TEXT COLLATE "C" NOT NULL DEFAULT '',
  updated_by      INTEGER,
  updated_at      TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

