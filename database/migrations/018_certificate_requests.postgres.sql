-- 직원의 증명서 발급 신청. 사업장 인사담당이 접수해 관리팀 내부 결재(전자결재 "증명서 발급 품의")로 발급합니다.
-- request 는 기재 항목·용도 등 신청 내용(JSON), workplace_code 등은 신청 당시 소속 사본(접수 사업장 판정용)입니다.
-- status: requested 접수 대기, processing 내부 결재 중(document_id), issued 발급(certificate_id), rejected 반려, cancelled 직원 취소
CREATE TABLE IF NOT EXISTS certificate_requests (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id     INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE,
  cert_type       TEXT COLLATE "C" NOT NULL CHECK (cert_type IN ('employment', 'career')),
  request         TEXT COLLATE "C" NOT NULL DEFAULT '{}',
  employee_name   TEXT COLLATE "C" NOT NULL,
  workplace_code  TEXT COLLATE "C",
  workplace       TEXT COLLATE "C",
  department      TEXT COLLATE "C",
  position        TEXT COLLATE "C",
  status          TEXT COLLATE "C" NOT NULL DEFAULT 'requested' CHECK (status IN ('requested', 'processing', 'issued', 'rejected', 'cancelled')),
  document_id     INTEGER REFERENCES approval_documents(id) ON DELETE SET NULL DEFERRABLE,
  certificate_id  INTEGER REFERENCES certificates(id) ON DELETE SET NULL DEFERRABLE,
  handler_id      INTEGER REFERENCES employees(id) ON DELETE SET NULL DEFERRABLE,
  handler_name    TEXT COLLATE "C",
  reject_reason   TEXT COLLATE "C",
  requested_at    TEXT COLLATE "C" NOT NULL,
  updated_at      TEXT COLLATE "C" NOT NULL,
  completed_at    TEXT COLLATE "C"
);

CREATE INDEX IF NOT EXISTS idx_certificate_requests_status ON certificate_requests(status, workplace_code);
CREATE INDEX IF NOT EXISTS idx_certificate_requests_employee ON certificate_requests(employee_id, requested_at);
