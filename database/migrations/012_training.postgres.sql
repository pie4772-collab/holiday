-- 법정의무교육 과정. code 는 기본 5개 과정의 고정 키이고, 관리자가 만든 과정은 NULL 입니다.
CREATE TABLE IF NOT EXISTS training_courses (
  id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                      TEXT COLLATE "C" UNIQUE,
  title                     TEXT COLLATE "C" NOT NULL,
  provider                  TEXT COLLATE "C" NOT NULL DEFAULT '',
  description               TEXT COLLATE "C" NOT NULL DEFAULT '',
  guidance                  TEXT COLLATE "C" NOT NULL DEFAULT '',
  company_material          TEXT COLLATE "C" NOT NULL DEFAULT '',
  require_material_confirm  INTEGER NOT NULL DEFAULT 0,
  sort_order                INTEGER NOT NULL DEFAULT 0,
  is_active                 INTEGER NOT NULL DEFAULT 1,
  created_at                TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at                TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

-- 과정의 교육 영상. youtube 는 페이지 안에서 재생하며 시청 시간을 기록하고, link 는 공식 사이트로 이동합니다.
CREATE TABLE IF NOT EXISTS training_videos (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id         INTEGER NOT NULL REFERENCES training_courses(id) ON DELETE CASCADE DEFERRABLE,
  title             TEXT COLLATE "C" NOT NULL,
  kind              TEXT COLLATE "C" NOT NULL CHECK (kind IN ('youtube', 'link')),
  video_ref         TEXT COLLATE "C" NOT NULL,
  duration_seconds  INTEGER,
  sort_order        INTEGER NOT NULL DEFAULT 0,
  created_at        TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS idx_training_videos_course ON training_videos(course_id, sort_order, id);

-- 연도별 교육 배정 (예: 2026년 성희롱 예방교육, 기한 2026-12-31)
CREATE TABLE IF NOT EXISTS training_sessions (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id    INTEGER NOT NULL REFERENCES training_courses(id) ON DELETE CASCADE DEFERRABLE,
  year         INTEGER NOT NULL,
  title        TEXT COLLATE "C" NOT NULL,
  start_date   TEXT COLLATE "C" NOT NULL,
  due_date     TEXT COLLATE "C" NOT NULL,
  status       TEXT COLLATE "C" NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  reminded_at  TEXT COLLATE "C",
  created_by   INTEGER,
  created_at   TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at   TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS idx_training_sessions_year ON training_sessions(year, due_date);

-- 교육 대상자와 수료 기록
CREATE TABLE IF NOT EXISTS training_assignees (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id             INTEGER NOT NULL REFERENCES training_sessions(id) ON DELETE CASCADE DEFERRABLE,
  employee_id            INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE,
  material_confirmed_at  TEXT COLLATE "C",
  completed_at           TEXT COLLATE "C",
  assigned_at            TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (session_id, employee_id)
);

CREATE INDEX IF NOT EXISTS idx_training_assignees_employee ON training_assignees(employee_id);

-- 영상별 시청 기록
CREATE TABLE IF NOT EXISTS training_progress (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignee_id       INTEGER NOT NULL REFERENCES training_assignees(id) ON DELETE CASCADE DEFERRABLE,
  video_id          INTEGER NOT NULL REFERENCES training_videos(id) ON DELETE CASCADE DEFERRABLE,
  watched_seconds   INTEGER NOT NULL DEFAULT 0,
  duration_seconds  INTEGER,
  opened_at         TEXT COLLATE "C",
  completed_at      TEXT COLLATE "C",
  updated_at        TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (assignee_id, video_id)
);

