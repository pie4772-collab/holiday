ALTER TABLE employees ADD COLUMN IF NOT EXISTS hire_type TEXT COLLATE "C";
ALTER TABLE employees ADD COLUMN IF NOT EXISTS probation_end TEXT COLLATE "C";
ALTER TABLE employees ADD COLUMN IF NOT EXISTS regular_date TEXT COLLATE "C";

-- 수습평가(신입 3개월)·3개월 평가(경력)·입사 1년 평가(신입). 수습을 연장하면 round 를 올려 한 번 더 만듭니다.
CREATE TABLE IF NOT EXISTS employee_evaluations (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id     INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE,
  kind            TEXT COLLATE "C" NOT NULL CHECK (kind IN ('probation', 'three_month', 'one_year')),
  round           INTEGER NOT NULL DEFAULT 1,
  due_date        TEXT COLLATE "C" NOT NULL,
  status          TEXT COLLATE "C" NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'submitted', 'confirmed', 'cancelled')),
  evaluator_id    INTEGER REFERENCES employees(id) ON DELETE SET NULL DEFERRABLE,
  scores          TEXT COLLATE "C",
  total_score     INTEGER,
  max_score       INTEGER,
  grade           TEXT COLLATE "C",
  comment         TEXT COLLATE "C",
  recommendation  TEXT COLLATE "C",
  outcome         TEXT COLLATE "C",
  outcome_date    TEXT COLLATE "C",
  hr_note         TEXT COLLATE "C",
  submitted_by    INTEGER,
  submitted_at    TEXT COLLATE "C",
  confirmed_by    INTEGER,
  confirmed_at    TEXT COLLATE "C",
  record_id       INTEGER,
  reminded_at     TEXT COLLATE "C",
  created_at      TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at      TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (employee_id, kind, round)
);

CREATE INDEX IF NOT EXISTS idx_employee_evaluations_status ON employee_evaluations(status, due_date);
CREATE INDEX IF NOT EXISTS idx_employee_evaluations_evaluator ON employee_evaluations(evaluator_id, status);
