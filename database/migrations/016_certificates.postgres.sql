-- 증명서 발급대장. content 는 발급 당시 기재 내용 사본(JSON)이라 다시 인쇄해도 그대로 나옵니다.
-- items 는 직원이 요청한 기재 항목(JSON 배열)입니다. 근로기준법 제39조: 요구한 사항만 적습니다.
CREATE TABLE IF NOT EXISTS certificates (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cert_type       TEXT COLLATE "C" NOT NULL CHECK (cert_type IN ('employment', 'career', 'retirement')),
  employee_id     INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE,
  year            INTEGER NOT NULL,
  seq             INTEGER NOT NULL,
  cert_no         TEXT COLLATE "C" NOT NULL UNIQUE,
  verify_code     TEXT COLLATE "C" NOT NULL,
  purpose         TEXT COLLATE "C" NOT NULL,
  submit_to       TEXT COLLATE "C" NOT NULL DEFAULT '',
  items           TEXT COLLATE "C" NOT NULL DEFAULT '[]',
  content         TEXT COLLATE "C" NOT NULL DEFAULT '{}',
  show_seal       INTEGER NOT NULL DEFAULT 1,
  channel         TEXT COLLATE "C" NOT NULL CHECK (channel IN ('self', 'admin', 'approval')),
  document_id     INTEGER REFERENCES approval_documents(id) ON DELETE SET NULL DEFERRABLE,
  issued_by       INTEGER REFERENCES employees(id) ON DELETE SET NULL DEFERRABLE,
  issued_by_name  TEXT COLLATE "C",
  issued_at       TEXT COLLATE "C" NOT NULL,
  status          TEXT COLLATE "C" NOT NULL DEFAULT 'issued' CHECK (status IN ('issued', 'revoked')),
  revoked_at      TEXT COLLATE "C",
  revoked_by      INTEGER REFERENCES employees(id) ON DELETE SET NULL DEFERRABLE,
  revoked_by_name TEXT COLLATE "C",
  revoke_reason   TEXT COLLATE "C",
  UNIQUE (year, seq)
);

CREATE INDEX IF NOT EXISTS idx_certificates_employee ON certificates(employee_id, issued_at);
