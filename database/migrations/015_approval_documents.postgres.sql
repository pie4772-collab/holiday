-- 범용 전자결재 문서. form_key 는 src/constants/approvalDocs.js 의 양식 키, body 는 양식 입력값 JSON 입니다.
-- 기안자 소속은 기안 당시 값을 사본으로 남깁니다. document_no 는 완료될 때 양식·연도별 일련번호로 매깁니다.
CREATE TABLE IF NOT EXISTS approval_documents (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_key            TEXT COLLATE "C" NOT NULL,
  title               TEXT COLLATE "C" NOT NULL,
  body                TEXT COLLATE "C" NOT NULL DEFAULT '{}',
  employee_id         INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE,
  drafter_name        TEXT COLLATE "C" NOT NULL,
  drafter_emp_no      TEXT COLLATE "C",
  drafter_workplace   TEXT COLLATE "C",
  drafter_department  TEXT COLLATE "C",
  drafter_position    TEXT COLLATE "C",
  status              TEXT COLLATE "C" NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'withdrawn')),
  current_step        INTEGER,
  doc_year            INTEGER,
  doc_seq             INTEGER,
  document_no         TEXT COLLATE "C" UNIQUE,
  source_id           INTEGER REFERENCES approval_documents(id) ON DELETE SET NULL DEFERRABLE,
  submitted_at        TEXT COLLATE "C" NOT NULL,
  completed_at        TEXT COLLATE "C",
  created_at          TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
  updated_at          TEXT COLLATE "C" NOT NULL DEFAULT to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS idx_approval_documents_employee ON approval_documents(employee_id, submitted_at);
CREATE INDEX IF NOT EXISTS idx_approval_documents_status ON approval_documents(status, form_key);

-- 결재 단계. role 은 팀장·임원·대표이사·공장장·담당·관리자·인사 이고, 결재할 사람은 처리할 때 판정합니다.
CREATE TABLE IF NOT EXISTS approval_document_steps (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id     INTEGER NOT NULL REFERENCES approval_documents(id) ON DELETE CASCADE DEFERRABLE,
  step_order      INTEGER NOT NULL,
  role            TEXT COLLATE "C" NOT NULL,
  status          TEXT COLLATE "C" NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'pending', 'approved', 'rejected', 'skipped')),
  actor_id        INTEGER REFERENCES employees(id) ON DELETE SET NULL DEFERRABLE,
  actor_name      TEXT COLLATE "C",
  actor_position  TEXT COLLATE "C",
  proxy           INTEGER NOT NULL DEFAULT 0,
  comment         TEXT COLLATE "C",
  acted_at        TEXT COLLATE "C",
  UNIQUE (document_id, step_order)
);

-- 참조자
CREATE TABLE IF NOT EXISTS approval_document_refs (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id  INTEGER NOT NULL REFERENCES approval_documents(id) ON DELETE CASCADE DEFERRABLE,
  employee_id  INTEGER NOT NULL REFERENCES employees(id) ON DELETE CASCADE DEFERRABLE,
  read_at      TEXT COLLATE "C",
  UNIQUE (document_id, employee_id)
);

CREATE INDEX IF NOT EXISTS idx_approval_document_refs_employee ON approval_document_refs(employee_id);
